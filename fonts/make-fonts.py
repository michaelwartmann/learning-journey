"""Builds the self-hosted fonts in this folder (no Google Fonts: blocked in China, and it leaks visits).

The fonts are cut down to the characters this site actually uses, so the Chinese fonts stay small.
Run it again after adding text with new characters:

    pip install fonttools brotli
    python3 fonts/make-fonts.py /path/to/source-ttfs

Source TTFs come from https://github.com/google/fonts (all SIL Open Font License, see OFL.txt).
Characters a font doesn't have fall back to the phone's own fonts.
"""
import pathlib, sys, re
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "fonts"
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")

text = ""
for p in ROOT.rglob("*"):
    if p.suffix in {".html", ".js", ".json", ".css", ".md"} and ".git" not in p.parts and p.parent != OUT:
        text += p.read_text(encoding="utf-8", errors="ignore")
used = set(text)
cjk = {c for c in used if re.match(r"[⺀-鿿　-〿＀-￯豈-﫿]", c)}
latin = set(map(chr, range(0x20, 0x7f))) | set(map(chr, range(0xa0, 0x100))) | set("āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüĀÁǍÀĒÉĚÈĪÍǏÌŌÓǑÒŪÚǓÙ‘’“”–—…•·€→←↑↓✓✕‹›")
latin |= {c for c in used if ord(c) < 0x2e80}

# family, source file, css style, css weight, characters, pin axes
FONTS = [
    ("Noto Sans", "NotoSans[wdth,wght].ttf", "normal", "400 700", latin, {"wdth": 100, "wght": (400, 700)}),
    ("Noto Serif", "NotoSerif[wdth,wght].ttf", "normal", "400 900", latin, {"wdth": 100, "wght": (400, 900)}),
    ("Source Serif 4", "SourceSerif4[opsz,wght].ttf", "normal", "400 700", latin, {"opsz": 20, "wght": (400, 700)}),
    ("Source Serif 4", "SourceSerif4-Italic[opsz,wght].ttf", "italic", "400", latin, {"opsz": 20, "wght": 400}),
    ("Playfair Display", "PlayfairDisplay[wght].ttf", "normal", "700 900", latin, {"wght": (700, 900)}),
    ("Playfair Display", "PlayfairDisplay-Italic[wght].ttf", "italic", "400", latin, {"wght": 400}),
    ("IBM Plex Mono", "IBMPlexMono-Medium.ttf", "normal", "500", latin, None),
    ("IBM Plex Mono", "IBMPlexMono-SemiBold.ttf", "normal", "600", latin, None),
    ("Noto Sans SC", "NotoSansSC[wght].ttf", "normal", "400 700", cjk | latin, {"wght": (400, 700)}),
    ("Noto Serif SC", "NotoSerifSC[wght].ttf", "normal", "400 900", cjk | latin, {"wght": (400, 900)}),
    ("Ma Shan Zheng", "MaShanZheng-Regular.ttf", "normal", "400", cjk, None),
]

css = ["/* Generated by make-fonts.py. Fonts: SIL Open Font License 1.1 (OFL.txt). */"]
for fam, src, style, weight, chars, axes in FONTS:
    font = TTFont(SRC / src, lazy=False)
    opts = subset.Options(); opts.layout_features = ["*"]; opts.name_IDs = ["*"]
    s = subset.Subsetter(opts); s.populate(text="".join(chars)); s.subset(font)
    if axes:
        font = instancer.instantiateVariableFont(font, axes)
    name = re.sub(r"[^a-z0-9]+", "-", f"{fam} {style} {weight}".lower()).strip("-") + ".woff2"
    font.flavor = "woff2"; font.save(OUT / name)
    print(f"{name:32} {(OUT / name).stat().st_size // 1024:5} KB")
    css.append(f'@font-face{{font-family:"{fam}";font-style:{style};font-weight:{weight};font-display:swap;src:url({name}) format("woff2")}}')
(OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
print(len(cjk), "Chinese characters")
